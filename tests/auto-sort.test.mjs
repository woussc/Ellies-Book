test('learning requires an explicit category choice; Not now stays quiet only in this project and session',()=>{
  const b=project(),entry={payee:'Netflix',categoryId:'category-1'};
  assert.equal(shouldOfferRule(b,entry,false),false);
  assert.equal(shouldOfferRule(b,entry,true),true);
  const learned=rememberPayee(b,entry.payee,entry.categoryId);
  assert.equal(shouldOfferRule(learned,entry,true),false);
  assert.equal(shouldOfferRule(learned,{...entry,categoryId:'category-2'},true),true);
  const values=new Map(),session={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
  dismissPayeeOffer(session,b,' Netflix ');
  assert.equal(isPayeeOfferDismissed(session,b,'NETFLIX'),true);
  assert.equal(isPayeeOfferDismissed(session,{...b,id:'other-project'},'Netflix'),false);
  assert.equal(isPayeeOfferDismissed(session,{...b,profile:'Team'},'Netflix'),false);
  assert.equal(isPayeeOfferDismissed({getItem:()=>null},b,'Netflix'),false);
});
for (const mode of ['Household','Just me','Team']) test(`${mode}: exact payee, isolated project, reversible preference-only changes and backup`,()=>{
  const b=project(mode), c=b.categories[1].id, next=rememberPayee(b,' Netflix ',c), rule=next.autoSortRules[0];
  assert.equal(suggestCategory(next,' NETFLIX ').categoryId,c);
  for(const other of ['Netflix Games','NETFLIX.COM','NETFL1X','']) assert.equal(suggestCategory(next,other),null);
  assert.equal(suggestCategory(project(mode),'Netflix'),null);
  assert.equal(suggestCategory({...next,profile:mode==='Team'?'Household':'Team'},'Netflix'),null);
  assert.equal(suggestCategory(openPeriod(next,'2026-12'),'Netflix').id,rule.id);
  const edited=rememberPayee(next,'netflix',b.categories[2].id);
  assert.equal(edited.autoSortRules.length,1);
  assert.equal(edited.autoSortRules[0].id,rule.id);
  assert.deepEqual(totals(edited),totals(b));assert.equal(edited.expenses,b.expenses);
  assert.deepEqual(parseBook(serializeBook(edited)),edited);
  const library=changeLibrary(emptyLibrary(),{type:'book',name:'Home',project:edited});
  assert.deepEqual(parseLibrary(serializeLibrary(library)),library);
  const restored=restoreLibrary(library,serializeLibrary(library));
  assert.notEqual(restored.books[1].projects[0].id,b.id);
  assert.deepEqual(restored.books[1].projects[0].autoSortRules,edited.autoSortRules);
  const paused=changePayeeRule(edited,rule.id,{paused:true});assert.equal(suggestCategory(paused,'Netflix'),null);
  assert.equal(suggestCategory(changePayeeRule(paused,rule.id,{paused:false}),'Netflix').categoryId,b.categories[2].id);
  const removed=removePayeeRule(next,rule.id);assert.equal(suggestCategory(removed,'Netflix'),null);
  assert.deepEqual(undoPayeeRule(removed,rule,null).autoSortRules,next.autoSortRules);
  assert.equal(undoPayeeRule(next,null,rule).autoSortRules.length,0);
  assert.throws(()=>undoPayeeRule(edited,null,rule),/changed/);
  assert.equal(suggestCategory({...next,categories:next.categories.filter(c=>c.id!==rule.categoryId)},'Netflix'),null);
});
